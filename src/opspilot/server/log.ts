/**
 * Structured logging.
 *
 * Every line is one JSON object on stdout/stderr so a log aggregator can index it
 * without a parser. Secrets never reach a log line: anything whose key looks like a
 * credential is replaced by `[redacted]`, and values that look like bearer tokens are
 * masked even in free-text fields.
 *
 * This module must stay dependency-free and free of Node-only imports: it is used
 * from route handlers, the job runner and (indirectly) middleware.
 */

export type LogLevel = "debug" | "info" | "warn" | "error";

export type LogFields = Record<string, unknown>;

const LEVEL_RANK: Record<LogLevel, number> = { debug: 10, info: 20, warn: 30, error: 40 };
const SECRET_KEY = /(pass|secret|token|api[-_]?key|authorization|cookie|credential|signature)/i;
const BEARER = /\b(?:bearer\s+)[A-Za-z0-9._~+/-]{8,}=*/gi;
const HEX_TOKEN = /\b[a-f0-9]{64}\b/gi;

function levelThreshold(): LogLevel {
  const raw = (process.env.LOG_LEVEL ?? "").trim().toLowerCase();
  return raw === "debug" || raw === "info" || raw === "warn" || raw === "error" ? raw : "info";
}

/** Masks obvious credentials inside free text (error messages, URLs). */
export function redactText(value: string): string {
  return value.replace(BEARER, "Bearer [redacted]").replace(HEX_TOKEN, "[redacted]");
}

function sanitise(value: unknown, depth = 0): unknown {
  if (value === null || value === undefined) return value;
  if (typeof value === "string") return redactText(value);
  if (typeof value === "number" || typeof value === "boolean") return value;
  if (value instanceof Date) return value.toISOString();
  if (value instanceof Error) return { name: value.name, message: redactText(value.message) };
  if (depth > 3) return "[truncated]";
  if (Array.isArray(value)) return value.slice(0, 20).map((item) => sanitise(item, depth + 1));
  if (typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const [key, inner] of Object.entries(value as Record<string, unknown>).slice(0, 40)) {
      out[key] = SECRET_KEY.test(key) ? "[redacted]" : sanitise(inner, depth + 1);
    }
    return out;
  }
  return String(value);
}

/**
 * Emits one structured line. Never throws: logging must not be able to break a request.
 */
export function log(level: LogLevel, event: string, fields: LogFields = {}): void {
  if (LEVEL_RANK[level] < LEVEL_RANK[levelThreshold()]) return;
  const line = JSON.stringify({
    ts: new Date().toISOString(),
    level,
    service: "opspilot",
    event,
    ...(sanitise(fields) as Record<string, unknown>),
  });
  if (level === "error" || level === "warn") console.error(line);
  else console.log(line);
}

export const logInfo = (event: string, fields?: LogFields) => log("info", event, fields);
export const logWarn = (event: string, fields?: LogFields) => log("warn", event, fields);
export const logError = (event: string, error: unknown, fields: LogFields = {}) =>
  log("error", event, { ...fields, error: error instanceof Error ? { name: error.name, message: error.message } : String(error) });

/** Correlation id for a request; generated by middleware when absent. */
export function newRequestId(): string {
  return globalThis.crypto?.randomUUID?.() ?? `req_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`;
}

export function requestIdFrom(request: Request): string {
  const header = request.headers.get("x-request-id");
  return header && /^[A-Za-z0-9._-]{8,80}$/.test(header) ? header : newRequestId();
}
